// Turns a session recorded by capture-live.cjs into a harness scene.
//
// The hand-written fixtures are precise but circular — they encode our reading
// of the Go source, so if we misread it they reproduce the misreading and the
// harness renders the wrong thing confidently. A recorded session cannot lie.
// This replays the JSONL through the same upsert rules chatSession.ts applies
// (merge on toolCallId, never let a contentless update wipe earlier output)
// and writes the resulting transcript out as a scene module.
//
//   node tools/visual/fixtures-from-live.cjs <in.jsonl> <out.ts> "<title>"

const fs = require('node:fs')
const path = require('node:path')

const [IN, OUT, TITLE] = [
  path.resolve(process.argv[2]),
  path.resolve(process.argv[3] || 'tools/visual/fixtures.live.ts'),
  process.argv[4] || 'Recorded session'
]

const items = []
const byId = new Map()
let msgSeq = 0

function textOf(content) {
  if (!Array.isArray(content)) return ''
  return content
    .map((b) => (b?.content?.type === 'text' ? b.content.text : b?.text || ''))
    .filter(Boolean)
    .join('\n')
}

for (const line of fs.readFileSync(IN, 'utf8').split('\n')) {
  if (!line.trim()) continue
  const u = JSON.parse(line).update ?? JSON.parse(line)
  const kind = u.sessionUpdate

  if (kind === 'agent_message_chunk' || kind === 'user_message_chunk') {
    const role = kind === 'user_message_chunk' ? 'user' : 'assistant'
    const last = items[items.length - 1]
    const text = u.content?.text ?? ''
    if (last?.kind === 'message' && last.message.role === role) last.message.text += text
    else
      items.push({
        kind: 'message',
        message: {
          id: `msg_${++msgSeq}`,
          role,
          text,
          attachments: [],
          isStreaming: false,
          timestamp: 1700000000000 + items.length * 1000
        }
      })
    continue
  }

  if (kind !== 'tool_call' && kind !== 'tool_call_update') continue
  const id = u.toolCallId
  if (!id) continue
  const output = textOf(u.content)

  let tool = byId.get(id)
  if (!tool) {
    tool = {
      id,
      title: u.title ?? 'Tool call',
      status: u.status ?? (kind === 'tool_call' ? 'in_progress' : 'completed'),
      output,
      diffs: [],
      // ToolCallItem.locations: { path, line? } (src/shared/model.ts).
      locations: (u.locations || [])
        .map((l) => (typeof l === 'string' ? { path: l } : l))
        .filter((l) => l && typeof l.path === 'string')
        .map((l) => (typeof l.line === 'number' ? { path: l.path, line: l.line } : { path: l.path })),
      timestamp: 1700000000000 + items.length * 1000
    }
    if (u.kind !== undefined) tool.kind = u.kind
    if (u.rawInput !== undefined) tool.argsJSON = JSON.stringify(u.rawInput)
    byId.set(id, tool)
    items.push({ kind: 'tool', tool })
    continue
  }
  if (u.title !== undefined) tool.title = u.title
  if (u.kind !== undefined) tool.kind = u.kind
  if (u.status !== undefined) tool.status = u.status
  // Same rule as the app: a contentless update must not erase earlier output.
  if (output !== '') tool.output = output
  if (u.rawInput !== undefined) tool.argsJSON = JSON.stringify(u.rawInput)
}

const header = `// GENERATED by tools/visual/fixtures-from-live.cjs — do not edit by hand.
//
// A real ACP session, replayed through the same upsert rules chatSession.ts
// uses. This is the scene that is allowed to contradict the hand-written
// fixtures: when it does, the hand-written ones are wrong.
//
// Source: ${path.basename(IN)}

import type { Scene } from './fixtures'

export const LIVE_SCENE: Scene = {
  id: 'live',
  title: ${JSON.stringify(TITLE)},
  note: 'Recorded from a real \`spettro --acp\` turn. Every field is exactly what the CLI put on the wire.',
  items: ${JSON.stringify(items, null, 2).split('\n').join('\n  ')} as never
}
`
fs.writeFileSync(OUT, header)
console.log(`${OUT}: ${items.length} items, ${byId.size} tool calls`)
